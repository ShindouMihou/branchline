// @vitest-environment happy-dom
import { vi, it, expect } from 'vitest';
const { invoke } = vi.hoisted(()=>({invoke:vi.fn()}));
vi.mock('@tauri-apps/api/core',()=>({invoke,isTauri:()=>false}));
vi.mock('@tauri-apps/plugin-dialog',()=>({open:vi.fn()}));
it('submits the network dialog and keeps the workbench below notifications',async()=>{
  const repo={root:'/repo',name:'test',branch:'main',branchRef:'refs/heads/main',head:'a'.repeat(40),stateToken:'token',files:[],stagedToken:'',remotes:['origin'],tracking:{upstream:'origin/main',ahead:1,behind:0,remote:'origin',merge:'main'},operation:null};
  invoke.mockImplementation(async(_command,args)=>args.request.op==='history'?[]:args.request.op==='branches'?[{reference:'refs/heads/main',name:'main',oid:repo.head,upstream:'origin/main',remote:false,current:true}]:repo);
  document.body.innerHTML='<div id="app"></div>';
  await import('./main');
  (document.getElementById('repo-path') as HTMLInputElement).value='/repo';document.getElementById('open-path')!.click();
  await vi.waitFor(()=>expect(document.getElementById('branches')).not.toBeNull());
  expect(document.getElementById('open')?.textContent).toContain('test');
  expect(document.querySelector('.clean-state')?.textContent).toContain('All clear');
  document.getElementById('appearance')!.click();
  const size=document.getElementById('ui-font-size') as HTMLInputElement;
  size.value='17';size.dispatchEvent(new Event('input',{bubbles:true}));
  expect(document.documentElement.style.getPropertyValue('--ui-font')).toBe('17px');
  expect(JSON.parse(localStorage.getItem('branchline.appearance.v1')!).fontSize).toBe(17);
  const code=document.getElementById('code-font-size') as HTMLInputElement;code.value='19';code.dispatchEvent(new Event('input',{bubbles:true}));
  expect(document.documentElement.style.getPropertyValue('--code-font')).toBe('19px');
  (document.querySelector('input[name="spacing"][value="relaxed"]') as HTMLInputElement).click();
  expect(document.documentElement.dataset.spacing).toBe('relaxed');
  const contrast=document.getElementById('dark-contrast') as HTMLInputElement;contrast.value='80';contrast.dispatchEvent(new Event('input',{bubbles:true}));
  expect(JSON.parse(localStorage.getItem('branchline.appearance.v1')!).contrast).toBe(80);
  document.getElementById('appearance-done')!.click();
  document.getElementById('appearance')!.click();
  expect((document.getElementById('ui-font-size') as HTMLInputElement).value).toBe('17');
  expect((document.getElementById('code-font-size') as HTMLInputElement).value).toBe('19');
  document.getElementById('reset-appearance')!.click();
  expect(document.documentElement.style.getPropertyValue('--ui-font')).toBe('14px');
  expect(document.documentElement.dataset.simplified).toBe('true');
  document.getElementById('appearance-done')!.click();
  expect(document.getElementById('sync')).toBeNull();
  expect(document.getElementById('refresh')).toBeNull();
  document.getElementById('update-options')!.click();
  expect(document.querySelector('.remote-badge')?.textContent).toContain('origin/main');
  expect(document.querySelector('.outgoing')?.getAttribute('aria-label')).toBe('1 outgoing commits');
  document.getElementById('fetch-only')!.click();
  await vi.waitFor(()=>expect(invoke).toHaveBeenCalledWith('request',{request:{op:'network',kind:'fetch',remote:'origin',branch:'',expected_head:'token'}}));
  await vi.waitFor(()=>expect(document.querySelector('.banner')?.textContent).toContain('Remote checked'));
  expect(invoke.mock.calls.filter(([,args])=>args.request.op==='network').map(([,args])=>args.request.kind)).toEqual(['fetch']);
  document.getElementById('update')!.click();
  expect(document.getElementById('dialog-title')?.textContent).toBe('Update branch');
  expect(document.querySelector('.operation-preview')?.textContent).toContain('Fetch the latest commits');
  document.getElementById('dialog-submit')!.click();
  await vi.waitFor(()=>expect(invoke).toHaveBeenCalledWith('request',{request:{op:'network',kind:'pull',remote:'origin',branch:'main',expected_head:'token'}}));
  await vi.waitFor(()=>expect(document.querySelector('.modal')).toBeNull());
  (document.querySelector('[data-network="push"]') as HTMLButtonElement).click();
  expect(document.getElementById('dialog-submit')).not.toBeNull();
  document.getElementById('dialog-submit')!.focus();document.getElementById('dialog-submit')!.click();
  await vi.waitFor(()=>expect(invoke).toHaveBeenCalledWith('request',{request:{op:'network',kind:'push',remote:'origin',branch:'main',expected_head:'token'}}));
  await vi.waitFor(()=>expect(document.querySelector('.modal')).toBeNull());
  expect(document.querySelector('.banner')?.textContent).toContain('Commits pushed');
  expect(document.querySelector('.rail')?.parentElement?.className).toBe('workbench');
  document.getElementById('branches')!.click();
  await vi.waitFor(()=>expect(document.getElementById('branch-filter')).not.toBeNull());
  const branchSearch=document.getElementById('branch-filter') as HTMLInputElement;branchSearch.value='feature/readable';branchSearch.dispatchEvent(new Event('input',{bubbles:true}));
  expect(document.querySelector('.branch-empty')?.textContent).toContain('No matching branches');
  expect(document.querySelector('.branch-list .group-heading')).toBeNull();
  document.getElementById('new-branch')!.click();
  expect((document.getElementById('new-branch-name') as HTMLInputElement).value).toBe('feature/readable');
  expect(document.querySelector('.dialog-note')?.textContent).toContain('Start from main');
  expect(document.querySelector('.dialog-note')?.textContent).not.toContain(repo.head);
  document.getElementById('dialog-close')?.click();
  const changed={...repo,files:[{path:'example.txt',old_path:null,index:'M',worktree:'M'}]};
  invoke.mockImplementation(async(_command,args)=>args.request.op==='stash'||args.request.op==='branches'||args.request.op==='history'?[]:args.request.op==='diff'?{patch:'@@ -1 +1 @@\n-old\n+new\n'}:changed);
  document.dispatchEvent(new KeyboardEvent('keydown',{key:'r',metaKey:true,bubbles:true}));
  await vi.waitFor(()=>expect(document.getElementById('changes-unstaged-toggle')).not.toBeNull());
  document.getElementById('changes-unstaged-toggle')!.click();
  expect(document.getElementById('changes-unstaged-toggle')?.getAttribute('aria-expanded')).toBe('false');
  expect(document.getElementById('changes-unstaged-files')?.hasAttribute('hidden')).toBe(true);
  expect(document.querySelectorAll('#changes-staged-files .file-row')).toHaveLength(1);
  document.getElementById('changes-staged-toggle')!.click();
  document.dispatchEvent(new KeyboardEvent('keydown',{key:'r',metaKey:true,bubbles:true}));
  await vi.waitFor(()=>expect(document.querySelector('.shell')?.getAttribute('aria-busy')).toBe('false'));
  expect(document.getElementById('changes-staged-toggle')?.getAttribute('aria-expanded')).toBe('false');
  document.getElementById('changes-unstaged-toggle')!.click();
  expect(document.querySelectorAll('#changes-unstaged-files .file-row')).toHaveLength(1);
  expect(document.getElementById('changes-unstaged-toggle')).toBe(document.activeElement);

  (document.querySelector('[data-tab="stashes"]') as HTMLButtonElement).click();
  await vi.waitFor(()=>expect(document.querySelector('.stash-empty')?.textContent).toContain('A place to pause your work'));
  expect(invoke).toHaveBeenCalledWith('request',{request:{op:'stash',request:{action:'list',expected_root:'/repo'}}});
  expect(document.querySelector('.workspace')).toBeNull();


});
